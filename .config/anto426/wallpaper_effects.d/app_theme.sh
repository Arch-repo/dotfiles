#!/usr/bin/env bash

gtk_theme_exists() {
    local theme="$1"

    [[ -d "$HOME/.themes/$theme" ]] ||
        [[ -d "$HOME/.local/share/themes/$theme" ]] ||
        [[ -d "/usr/share/themes/$theme" ]]
}

gtk_reload_theme() {
    local target_theme="${gtk_theme_name:-adw-gtk3-dark}"
    local bounce_theme=""
    local candidate

    command -v gsettings >/dev/null 2>&1 || return 0

    for candidate in adw-gtk3-dark adw-gtk3 Adwaita-dark Adwaita; do
        if [[ "$candidate" != "$target_theme" ]] && gtk_theme_exists "$candidate"; then
            bounce_theme="$candidate"
            break
        fi
    done

    if [[ -n "$bounce_theme" ]]; then
        gsettings set org.gnome.desktop.interface gtk-theme "$bounce_theme" 2>/dev/null || true
        gsettings set org.gnome.desktop.interface color-scheme "default" 2>/dev/null || true
        sleep 0.08
    fi

    gsettings set org.gnome.desktop.interface color-scheme "prefer-dark" 2>/dev/null || true
    gsettings set org.gnome.desktop.interface gtk-theme "$target_theme" 2>/dev/null || true
    gsettings set org.gnome.desktop.interface icon-theme "WhiteSur-dark" 2>/dev/null || true
    gsettings set org.gnome.desktop.interface cursor-theme "macOS" 2>/dev/null || true
    gsettings set org.gnome.desktop.interface font-name "Segoe UI Variable Static Text 12" 2>/dev/null || true
    gsettings set org.gnome.desktop.interface monospace-font-name "JetBrainsMono Nerd Font 12" 2>/dev/null || true
}

restart_gtk_portals() {
    if command -v systemctl >/dev/null 2>&1; then
        systemctl --user restart \
            xdg-desktop-portal-gtk.service \
            xdg-desktop-portal.service \
            xdg-desktop-portal-hyprland.service >/dev/null 2>&1 && return 0
    fi

    pkill -x xdg-desktop-portal-gtk 2>/dev/null || true
    pkill -x xdg-desktop-portal 2>/dev/null || true
}

