write_kvantum_theme() {
    local k_theme="anto426"
    local k_dir="$kvantum_dir/$k_theme"
    local base_svg="/usr/share/Kvantum/KvArcDark/KvArcDark.svg"
    local base_config="/usr/share/Kvantum/KvArcDark/KvArcDark.kvconfig"
    local use_base=0

    ensure_gtk_palette_roles

    mkdir -p "$kvantum_dir" "$k_dir"
    find "$kvantum_dir" -maxdepth 1 -type d \
        -iname 'anto426*' \
        ! -name "$k_theme" -exec rm -rf {} + 2>/dev/null || true

    [[ -r "$base_svg" && -r "$base_config" ]] && use_base=1

    if ((use_base)); then
        awk \
            -v bg="$surface" \
            -v base="$base" \
            -v fg="$foreground" \
            -v border="$border" \
            -v accent="$accent" '
            /#404552/ { gsub(/#404552/, bg) }
            /#383c4a/ { gsub(/#383c4a/, base) }
            /#4b5162/ { gsub(/#4b5162/, bg) }
            /#5294e2/ { gsub(/#5294e2/, accent) }
            /#0582ff/ { gsub(/#0582ff/, accent) }
            /#b74aff/ { gsub(/#b74aff/, border) }
            /#d3dae3/ { gsub(/#d3dae3/, fg) }
            /#151515/ { gsub(/#151515/, border) }
            /#000000/ { gsub(/#000000/, border) }
            { print }
        ' "$base_svg" >"$k_dir/$k_theme.svg"
    else
        cat >"$k_dir/$k_theme.svg" <<EOF
<svg width="96" height="96" version="1.1" xmlns="http://www.w3.org/2000/svg">
  <defs>
    <linearGradient id="anto426Button" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="$surface"/>
      <stop offset="1" stop-color="$background"/>
    </linearGradient>
  </defs>
	  <rect id="common" x="4" y="4" width="24" height="24" rx="6" fill="$surface" stroke="$border"/>
	  <rect id="button" x="36" y="4" width="24" height="24" rx="6" fill="url(#anto426Button)" stroke="$border"/>
	  <rect id="lineedit" x="68" y="4" width="24" height="24" rx="5" fill="$base" stroke="$border"/>
	  <rect id="focus" x="4" y="36" width="24" height="24" rx="6" fill="none" stroke="$accent" stroke-width="2"/>
  <rect id="tab" x="36" y="36" width="24" height="24" rx="5" fill="$select" stroke="$accent"/>
  <rect id="dock" x="68" y="36" width="24" height="24" rx="4" fill="$surface" stroke="$border"/>
  <circle id="radio" cx="16" cy="80" r="8" fill="$background" stroke="$accent" stroke-width="2"/>
  <rect id="checkbox" x="36" y="68" width="18" height="18" rx="4" fill="$background" stroke="$accent" stroke-width="2"/>
  <path id="arrow" d="M72 72 L84 80 L72 88 Z" fill="$foreground"/>
  <path id="arrow-down" d="M8 8 L20 8 L14 16 Z" fill="$foreground"/>
  <path id="spin" d="M44 70 L52 78 L44 86 Z" fill="$foreground"/>
</svg>
EOF
    fi

    if ((use_base)); then
        awk \
            -v background="$background" \
            -v base="$base" \
            -v base_alt="$base_alt" \
            -v surface="$surface" \
            -v select="$select" \
            -v accent="$accent" \
            -v border="$border" \
            -v foreground="${foreground}c8" \
            -v muted="${muted}99" \
            -v tooltip="$foreground" \
            -v highlight_text="$selected_fg" '
            /^author=/ { print "author=anto426"; next }
            /^comment=/ { print "comment=Dynamic anto426 palette generated from the active wallpaper"; next }
            /^window.color=/ { print "window.color=" surface; next }
            /^base.color=/ { print "base.color=" base; next }
            /^alt.base.color=/ { print "alt.base.color=" base_alt; next }
            /^button.color=/ { print "button.color=" surface; next }
            /^light.color=/ { print "light.color=" select; next }
            /^mid.light.color=/ { print "mid.light.color=" border; next }
            /^dark.color=/ { print "dark.color=" background; next }
            /^mid.color=/ { print "mid.color=" border; next }
            /^highlight.color=/ { print "highlight.color=" accent; next }
            /^inactive.highlight.color=/ { print "inactive.highlight.color=" select; next }
            /^text.color=/ { print "text.color=" foreground; next }
            /^window.text.color=/ { print "window.text.color=" foreground; next }
            /^button.text.color=/ { print "button.text.color=" foreground; next }
            /^disabled.text.color=/ { print "disabled.text.color=" muted; next }
            /^tooltip.text.color=/ { print "tooltip.text.color=" tooltip; next }
            /^highlight.text.color=/ { print "highlight.text.color=" highlight_text; next }
            /^link.color=/ { print "link.color=" accent; next }
            /^link.visited.color=/ { print "link.visited.color=" select; next }
            /^menu_shadow_depth=/ { print "menu_shadow_depth=0"; next }
            /^tooltip_shadow_depth=/ { print "tooltip_shadow_depth=0"; next }
            /^blurring=/ { print "blurring=false"; next }
            /^popup_blurring=/ { print "popup_blurring=false"; next }
            { print }
        ' "$base_config" >"$k_dir/$k_theme.kvconfig"
    else
        cat >"$k_dir/$k_theme.kvconfig" <<EOF
[%General]
author=anto426
comment=Dynamic anto426 palette generated from the active wallpaper
x11drag=menubar_and_primary_toolbar
alt_mnemonic=true
left_tabs=true
attach_active_tab=true
mirror_doc_tabs=true
composite=true
menu_shadow_depth=0
tooltip_shadow_depth=0
scroll_width=9
scroll_arrows=false
slider_width=6
slider_handle_width=18
check_size=14
menubar_mouse_tracking=true
toolbutton_style=1
translucent_windows=false
blurring=false
popup_blurring=false
merge_menubar_with_toolbar=true
small_icon_size=16
large_icon_size=32
button_icon_size=16
toolbar_icon_size=22
layout_spacing=6
layout_margin=9
scrollbar_in_view=true
transient_scrollbar=true
submenu_overlap=3

[GeneralColors]
window.color=$surface
base.color=$base
alt.base.color=$base_alt
button.color=$surface
light.color=$select
mid.light.color=$border
dark.color=$background
mid.color=$border
highlight.color=$accent
inactive.highlight.color=$select
text.color=${foreground}c8
window.text.color=${foreground}c8
button.text.color=${foreground}c8
disabled.text.color=${muted}99
tooltip.text.color=$foreground
highlight.text.color=$selected_fg
link.color=$accent
link.visited.color=$select
progress.indicator.text.color=$selected_fg

[PanelButtonCommand]
frame=true
frame.element=button
frame.top=3
frame.bottom=3
frame.left=3
frame.right=3
interior=true
interior.element=button
indicator.size=9
indicator.element=arrow
text.normal.color=${foreground}c8
text.focus.color=$foreground
text.press.color=$foreground
text.toggle.color=$foreground
text.shadow=0
text.margin=1
text.iconspacing=4
min_width=+0.3font
min_height=+0.3font
frame.expansion=6

[PanelButtonTool]
inherits=PanelButtonCommand

[Dock]
inherits=PanelButtonCommand
interior.element=dock
frame.element=dock

[RadioButton]
inherits=PanelButtonCommand
frame=false
interior.element=radio

[CheckBox]
inherits=PanelButtonCommand
frame=false
interior.element=checkbox

[Focus]
inherits=PanelButtonCommand
frame=true
frame.element=focus
interior=false

[GenericFrame]
inherits=PanelButtonCommand
frame=true
interior=false
frame.element=common

[LineEdit]
inherits=PanelButtonCommand
frame.element=lineedit
interior.element=lineedit

[DropDownButton]
inherits=PanelButtonCommand
indicator.element=arrow-down

[IndicatorArrow]
indicator.element=arrow
indicator.size=9

[IndicatorSpinBox]
inherits=PanelButtonCommand
indicator.element=spin
indicator.size=10

[Tab]
inherits=PanelButtonCommand
interior.element=tab
frame.element=tab
text.margin.left=8
text.margin.right=8

[Hacks]
respect_darkness=true
force_size_grip=true
iconless_pushbutton=true
normal_default_pushbutton=true
single_top_toolbar=true
EOF
    fi

    cat >"$kvantum_config_file" <<EOF
[General]
theme=$k_theme
EOF

    log "Kvantum theme attivo: $k_theme"
}

write_app_theme() {
    write_gtk_theme
    write_qt_theme
    write_kvantum_theme
    gtk_reload_theme
    restart_gtk_portals
}
