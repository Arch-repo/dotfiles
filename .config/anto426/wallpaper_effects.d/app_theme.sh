find_gtk_base_theme() {
    local theme="${ANTO426_GTK_BASE_THEME:-Anto426-Dark}"
    local candidate

    for candidate in \
        "$HOME/.themes/$theme" \
        "$HOME/.local/share/themes/$theme" \
        "/usr/share/themes/$theme" \
        "$HOME/.themes/Anto426" \
        "$HOME/.local/share/themes/Anto426" \
        "/usr/share/themes/Anto426"; do
        if [[ -d "$candidate" ]]; then
            printf '%s\n' "$candidate"
            return 0
        fi
    done

    return 1
}

copy_gtk_base_theme() {
    local target="$1"
    local base_theme

    rm -rf "$target"
    mkdir -p "$(dirname "$target")"

    if base_theme="$(find_gtk_base_theme)"; then
        cp -a "$base_theme" "$target"
        return 0
    fi

    mkdir -p "$target/gtk-3.0" "$target/gtk-4.0"
    return 1
}

# Convert a hex color like #aabbcc to decimal "r, g, b" for rgba() replacement
hex_to_rgb_triple() {
    local hex="${1#\#}"
    printf '%d, %d, %d' "0x${hex:0:2}" "0x${hex:2:2}" "0x${hex:4:2}"
}

