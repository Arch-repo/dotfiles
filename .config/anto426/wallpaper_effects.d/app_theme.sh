find_gtk_base_theme() {
    local theme="${ANTO426_GTK_BASE_THEME:-Anto426-Dark}"
    local candidate

    for candidate in \
        "$HOME/.themes/$theme" \
        "$HOME/.local/share/themes/$theme" \
        "/usr/share/themes/$theme" \
        "$HOME/.themes/Anto426" \
        "$HOME/.local/share/themes/Anto426" \
        "/usr/share/themes/Anto426"; do
        if [[ -d "$candidate" ]]; then
            printf '%s\n' "$candidate"
            return 0
        fi
    done

    return 1
}

copy_gtk_base_theme() {
    local target="$1"
    local base_theme

    rm -rf "$target"
    mkdir -p "$(dirname "$target")"

    if base_theme="$(find_gtk_base_theme)"; then
        cp -a "$base_theme" "$target"
        return 0
    fi

    mkdir -p "$target/gtk-3.0" "$target/gtk-4.0"
    return 1
}

prepare_gtk_overlay_target() {
    local target="$1"
    local gtk_dir="$2"
    local css_dir="$target/$gtk_dir"
    local base_css="base.css"
    local base_dark_css="base-dark.css"

    mkdir -p "$css_dir"

    if [[ -f "$css_dir/gtk.css" ]]; then
        mv "$css_dir/gtk.css" "$css_dir/$base_css"
    else
        base_css=""
    fi

    if [[ -f "$css_dir/gtk-dark.css" ]]; then
        mv "$css_dir/gtk-dark.css" "$css_dir/$base_dark_css"
    else
        base_dark_css="$base_css"
    fi

    write_gtk_css_file "$css_dir/gtk.css" "${gtk_dir#gtk-}" "$base_css"
    write_gtk_css_file "$css_dir/gtk-dark.css" "${gtk_dir#gtk-}" "$base_dark_css"
}

write_gtk_theme() {
    local theme_root
    local theme_share_root
    local target

    gtk_theme_name="anto426"
    theme_root="$HOME/.themes/$gtk_theme_name"
    theme_share_root="$HOME/.local/share/themes/$gtk_theme_name"

    mkdir -p "$HOME/.themes" "$HOME/.local/share/themes"
    find "$HOME/.themes" "$HOME/.local/share/themes" -maxdepth 1 -type d \
        -iname 'anto426*' \
        ! -name "$gtk_theme_name" -exec rm -rf {} + 2>/dev/null || true

    for target in "$theme_root" "$theme_share_root"; do
        copy_gtk_base_theme "$target" || true
        prepare_gtk_overlay_target "$target" "gtk-3.0"
        prepare_gtk_overlay_target "$target" "gtk-4.0"
        cat >"$target/index.theme" <<EOF
[X-GNOME-Metatheme]
Name=$gtk_theme_name
Type=X-GNOME-Metatheme
Comment=Dynamic anto426 GTK theme based on Anto426-theme
Encoding=UTF-8
GtkTheme=$gtk_theme_name
EOF
    done

    write_gtk_css_file "$gtk3_dir/gtk.css" "3.0"
    write_gtk_css_file "$gtk4_dir/gtk.css" "4.0"

    for gtk_settings_dir in "$gtk3_dir" "$gtk4_dir"; do
        cat >"$gtk_settings_dir/settings.ini" <<EOF
[Settings]
gtk-theme-name=$gtk_theme_name
gtk-icon-theme-name=WhiteSur-dark
gtk-cursor-theme-name=macOS
gtk-font-name=Segoe UI Variable Static Text 12
gtk-application-prefer-dark-theme=true
EOF
    done
}

