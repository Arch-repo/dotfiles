            ANTO426_SURFACE="$surface" \
            ANTO426_BASE="$base" \
            ANTO426_BASE_ALT="$base_alt" \
            ANTO426_SELECT="$select" \
            ANTO426_ACCENT="$accent" \
            ANTO426_FOREGROUND="$foreground" \
            ANTO426_MUTED="$muted" \
            ANTO426_BORDER="$border" \
            ANTO426_SELECTED_FG="$selected_fg" \
            ANTO426_RED="$red" \
