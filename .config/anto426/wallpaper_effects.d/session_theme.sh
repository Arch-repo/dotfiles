write_vscode_extension_stub() {
    local extension_dir="$HOME/.vscode/extensions/anto426.anto426-vscode-theme-dynamic"
    local generated_theme="$1"
    local tmp_package

    mkdir -p "$extension_dir/themes"
    tmp_package="$(mktemp)"
    cat >"$tmp_package" <<EOF
{
  "name": "anto426-vscode-theme",
  "displayName": "$vscode_theme_name",
  "description": "Dynamic VS Code theme generated by wallpaper_effects.sh.",
  "version": "0.1.0",
  "publisher": "Anto426",
  "engines": {
    "vscode": "^1.76.0"
  },
  "categories": ["Themes"],
  "contributes": {
    "themes": [
      {
        "label": "$vscode_theme_name",
        "uiTheme": "vs-dark",
        "path": "./themes/$vscode_theme_file"
      }
    ]
  }
}
EOF
    copy_if_changed "$tmp_package" "$extension_dir/package.json" || true
    rm -f "$tmp_package"
    copy_if_changed "$generated_theme" "$extension_dir/themes/$vscode_theme_file" || true
    log "VSCode theme stub aggiornato: $extension_dir"
}

copy_if_changed() {
    local src="$1"
    local dst="$2"

    mkdir -p "$(dirname "$dst")"
    if [[ -f "$dst" ]] && cmp -s "$src" "$dst"; then
        return 1
    fi

    cp "$src" "$dst"
}

vscode_is_running() {
    if command -v hyprctl >/dev/null 2>&1 &&
        hyprctl clients -j 2>/dev/null |
            grep -Eiq '"class"[[:space:]]*:[[:space:]]*"(Code|code|code-url-handler|code-oss|Code - OSS|codium|Codium|VSCodium|code-insiders|Code - Insiders)"'; then
        return 0
    fi

    if pgrep -x code >/dev/null 2>&1 ||
        pgrep -x codium >/dev/null 2>&1 ||
        pgrep -x code-oss >/dev/null 2>&1 ||
        pgrep -x code-insiders >/dev/null 2>&1 ||
        {
            pgrep -x electron >/dev/null 2>&1 &&
                pgrep -af '(^|[ /])(Code|VSCodium|code-oss|code-insiders)([ /]|$)|class=(Code|VSCodium|code-oss|code-insiders)' >/dev/null 2>&1
        }; then
        return 0
    fi

    return 1
}

write_vscode_user_settings() {
    local settings_dirs=(
        "$HOME/.config/Code/User"
        "$HOME/.config/Code - OSS/User"
        "$HOME/.config/VSCodium/User"
    )
    local settings_dir
    local settings_file
    local node_result

    for settings_dir in "${settings_dirs[@]}"; do
        [[ "$settings_dir" == "$HOME/.config/Code/User" || -d "$(dirname "$settings_dir")" ]] || continue
        mkdir -p "$settings_dir"
        settings_file="$settings_dir/settings.json"

        if command -v node >/dev/null 2>&1; then
            if node_result="$(ANTO426_BACKGROUND="$background" \
                ANTO426_SURFACE="$surface" \
                ANTO426_BASE="$base" \
                ANTO426_SELECT="$select" \
                ANTO426_ACCENT="$accent" \
                ANTO426_FOREGROUND="$foreground" \
                ANTO426_MUTED="$muted" \
                ANTO426_BORDER="$border" \
                ANTO426_RED="$red" \
                ANTO426_ORANGE="$orange" \
                ANTO426_YELLOW="$yellow" \
                ANTO426_GREEN="$green" \
                ANTO426_PINK="$pink" \
                node - "$settings_file" "$vscode_theme_name" <<'NODE'
const fs = require('fs')
const [settingsPath, themeName] = process.argv.slice(2)

function stripJsonc(text) {
  let output = ''
  let inString = false
  let escaped = false
  let inLineComment = false
  let inBlockComment = false

  for (let i = 0; i < text.length; i++) {
    const char = text[i]
    const next = text[i + 1]

    if (inLineComment) {
      if (char === '\n') {
        inLineComment = false
        output += char
      }
      continue
    }

    if (inBlockComment) {
      if (char === '*' && next === '/') {
        inBlockComment = false
        i++
      }
      continue
    }

    if (inString) {
      output += char
      if (escaped) {
        escaped = false
      } else if (char === '\\') {
        escaped = true
      } else if (char === '"') {
        inString = false
      }
      continue
    }

    if (char === '"') {
      inString = true
      output += char
      continue
    }

    if (char === '/' && next === '/') {
      inLineComment = true
      i++
      continue
    }

    if (char === '/' && next === '*') {
      inBlockComment = true
      i++
      continue
    }

    output += char
  }

  return output.replace(/,\s*([}\]])/g, '$1')
}

