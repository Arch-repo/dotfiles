write_vscode_theme() {
    local generated_theme="$tmp_dir/$vscode_theme_file"
    local roots=(
        "$HOME/.vscode/extensions"
        "$HOME/.vscode-oss/extensions"
        "$HOME/.vscodium/extensions"
    )
    local root
    local package_file
    local extension_dir
    local updated=0

    write_vscode_theme_json "$generated_theme"

    if vscode_is_running; then
        log "VSCode in esecuzione: salto aggiornamento file estensione per evitare reload."
    else
        for root in "${roots[@]}"; do
            [[ -d "$root" ]] || continue
            while IFS= read -r -d '' package_file; do
                if grep -Eq '"name"[[:space:]]*:[[:space:]]*"anto426-vscode-theme"' "$package_file"; then
                    extension_dir="$(dirname "$package_file")"
                    if copy_if_changed "$generated_theme" "$extension_dir/themes/$vscode_theme_file"; then
                        log "VSCode theme aggiornato: $extension_dir/themes/$vscode_theme_file"
                    else
                        log "VSCode theme invariato: $extension_dir/themes/$vscode_theme_file"
                    fi
                    updated=1
                fi
            done < <(find "$root" -maxdepth 2 -type f -name package.json -print0 2>/dev/null)
        done

        if ((updated == 0)); then
            write_vscode_extension_stub "$generated_theme"
        fi
    fi

    write_vscode_user_settings "$generated_theme"
}

write_htop_theme() {
    local target="$htop_config_dir/htoprc"
    local htop_version
    local tmp

    mkdir -p "$htop_config_dir"
    htop_version="$(htop --version 2>/dev/null | awk 'NR == 1 { print $2; exit }')"
    htop_version="${htop_version:-3.5.1}"

    if [[ -f "$target" ]]; then
        tmp="$(mktemp)"
        awk '
            BEGIN {
                seen_color = 0
                seen_base = 0
                seen_megabytes = 0
            }
            /^color_scheme=/ {
                print "color_scheme=0"
                seen_color = 1
                next
            }
            /^highlight_base_name=/ {
                print "highlight_base_name=1"
                seen_base = 1
                next
            }
            /^highlight_megabytes=/ {
                print "highlight_megabytes=1"
                seen_megabytes = 1
                next
            }
            { print }
            END {
                if (!seen_color) print "color_scheme=0"
                if (!seen_base) print "highlight_base_name=1"
                if (!seen_megabytes) print "highlight_megabytes=1"
            }
        ' "$target" >"$tmp"
        mv "$tmp" "$target"
        log "htop palette aggiornata: $target"
        return 0
    fi

