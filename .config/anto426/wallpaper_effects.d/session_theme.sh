    cat >"$colors_dir/colors.rasi" <<EOF
* {
    background: $background;
    surface: $surface;
    base: $base;
    base-alt: $base_alt;
    titlebar: $titlebar;
    titlebar-backdrop: $titlebar_backdrop;
    popover: $popover;
    panel-bg: $panel_bg;
    panel-bg-hover: $panel_bg_hover;
    overlay-bg: $overlay_bg;
    item-bg: $item_bg;
    item-bg-hover: $item_bg_hover;
    item-bg-active: $item_bg_active;
    accent-soft: $accent_soft;
    accent-strong: $accent_strong;
    border-soft: $border_soft;
    border-medium: $border_medium;
    shadow-soft: $shadow_soft;
    shadow-medium: $shadow_medium;
    background-alpha: $background_alpha;
    surface-alpha: $surface_alpha;
    foreground: $foreground;
    muted: $muted;
    select: $select;
    select-alpha: $select_alpha;

    accent: $accent;
    selected-fg: $selected_fg;
    accent-alpha: $accent_alpha;
    border: $border;
    border-alpha: $border_alpha;
    pink: $pink;
    purple: $purple;
    red: $red;
    orange: $orange;
    yellow: $yellow;
    green: $green;
    blue: @accent;
    cyan: @muted;
    gray: $gray;

    active-background: @select;
    urgent-background: @red;
    urgent-foreground: @background;
